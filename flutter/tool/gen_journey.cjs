// Regenerate lib/core/journey_data.dart from ../grid-journey.js (the 120 Journey
// specifications) and test/fixtures/journey_expected.json from the builder's
// measurements. Run from flutter/: node tool/gen_journey.cjs
const path = require('path'), fs = require('fs');
const root = path.join(__dirname, '..', '..');
const K = require(path.join(root, 'grid-journey.js'));
const num = x => Number.isInteger(x) ? x.toFixed(1) : String(x);
const rows = K.map(l => `  Spec(hex: ${l.grid === 'hex'}, w: ${l.W}, h: ${l.H}, difficulty: ${num(l.difficulty)}, mirrors: ${l.mirrors}, springs: ${l.springs}, seed: ${JSON.stringify(l.seed)}` +
  `${l.requireSlide ? ', requireSlide: true' : ''}${l.minMirrors ? ', minMirrors: ' + l.minMirrors : ''}${l.minSprings ? ', minSprings: ' + l.minSprings : ''}),`);
fs.writeFileSync(path.join(__dirname, '../lib/core/journey_data.dart'),
  '// Generated by tool/gen_journey.cjs from grid-journey.js: the 120 Journey specifications.\n' +
  "import 'gridgen.dart';\n\nconst List<Spec> journeySpecs = [\n" + rows.join('\n') + '\n];\n');
const M = require(path.join(root, 'scripts/grid-journey-measurements.json'));
fs.writeFileSync(path.join(__dirname, '../test/fixtures/journey_expected.json'),
  '[\n' + M.map(m => JSON.stringify({ grid: m.grid, W: m.W, H: m.H, layoutKey: m.layoutKey, par: m.par, ropeCount: m.ropeCount })).join(',\n') + '\n]\n');
