// Writes ../journey.ents, the 120 Journey specifications as a data table, from
// grid-journey.js of the reference (9e69e3a), as scripts/gen-journey.cjs writes
// src/core/journey.mbt from it:
//   node moonbit/encantis/core/oracle/gen-journey-ents.cjs [grid-journey.js]
// The default is the reference checkout of ref.cjs (MF_REF).
'use strict';
const path = require('path'), fs = require('fs');
const file = process.argv[2] || path.join(require('./ref.cjs').dir, 'grid-journey.js');
const K = require(path.resolve(file));
if (K.length !== 120) throw Error('expected 120 levels, got ' + K.length);
const num = x => Number.isInteger(x) ? x.toFixed(1) : String(x);
const rows = K.map(l => `  (hex: ${l.grid === 'hex'}, w: ${l.W}, h: ${l.H}, difficulty: ${num(l.difficulty)}, mirrors: ${l.mirrors}, springs: ${l.springs}, ` +
  `seed: ${JSON.stringify(l.seed)}, require_slide: ${!!l.requireSlide}, min_mirrors: ${l.minMirrors || 0}, min_springs: ${l.minSprings || 0}, colossal: false),`);
const out = `// Generated by oracle/gen-journey-ents.cjs from grid-journey.js (9e69e3a): the 120
// Journey specifications. Do not edit; run the script again.

// --- The canonical type block (Spec only) ---
type Spec = (hex: bool, w: i32, h: i32, difficulty: f64, mirrors: bool, springs: bool, seed: []u8,
             require_slide: bool, min_mirrors: i32, min_springs: i32, colossal: bool)
// --- end of the canonical type block ---

data specs: *[120]Spec = [
${rows.join('\n')}
]

// The Journey, level by level.
export func journey() -> []Spec => specs
`;
fs.writeFileSync(path.join(__dirname, '../journey.ents'), out);
console.log('wrote journey.ents:', K.length, 'levels');
