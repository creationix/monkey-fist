// Writes ../journey.ents, the Journey's 120 specifications as two data tables:
//   specs_js:   grid-journey.js of the reference (9e69e3a), the JS game's Journey, as
//               scripts/gen-journey.cjs writes src/core/journey.mbt from it;
//   specs_port: the Journey the seed search chose for the port's own generator
//               (oracle/journey-search.cjs writes it, as grid-journey.js's runtime source, to
//               fixtures/journey-port.js); the JS's table until that file exists.
// journey() gives specs_port unless use_js_journey(true) (the JS's mode, gen.ents).
//   node moonbit/encantis/core/oracle/gen-journey-ents.cjs [grid-journey.js [journey-port.js]]
// The defaults are the reference checkout of ref.cjs (MF_REF) and fixtures/journey-port.js.
'use strict';
const path = require('path'), fs = require('fs');
const jsFile = process.argv[2] || path.join(require('./ref.cjs').dir, 'grid-journey.js');
const portDefault = path.join(__dirname, 'fixtures/journey-port.js');
const portFile = process.argv[3] || (fs.existsSync(portDefault) ? portDefault : jsFile);
const load = file => {
  const K = require(path.resolve(file));
  if (K.length !== 120) throw Error(file + ': expected 120 levels, got ' + K.length);
  return K;
};
const num = x => Number.isInteger(x) ? x.toFixed(1) : String(x);
const rows = K => K.map(l => `  (hex: ${l.grid === 'hex'}, w: ${l.W}, h: ${l.H}, difficulty: ${num(l.difficulty)}, mirrors: ${l.mirrors}, springs: ${l.springs}, ` +
  `seed: ${JSON.stringify(l.seed)}, require_slide: ${!!l.requireSlide}, min_mirrors: ${l.minMirrors || 0}, min_springs: ${l.minSprings || 0}, colossal: false),`).join('\n');
const rel = f => path.relative(path.join(__dirname, '../../../..'), path.resolve(f));
const out = `// Generated by oracle/gen-journey-ents.cjs: the 120 Journey specifications, twice. Do not edit;
// run the script again.
//   specs_js:   from grid-journey.js at 9e69e3a, the JS game's Journey.
//   specs_port: from ${rel(portFile)}, the seeds the game's own seed search
//               (build-grid-journey.cjs's rules, oracle/journey-search.cjs) chose for the port's
//               generator, whose Hex levels differ from the JS's (hex_build's departures, G4).

// --- The canonical type block (Spec only) ---
type Spec = (hex: bool, w: i32, h: i32, difficulty: f64, mirrors: bool, springs: bool, seed: []u8,
             require_slide: bool, min_mirrors: i32, min_springs: i32, colossal: bool)
// --- end of the canonical type block ---

data specs_js: *[120]Spec = [
${rows(load(jsFile))}
]

data specs_port: *[120]Spec = [
${rows(load(portFile))}
]

// Which table journey() gives: the JS's (true) or the port's (false, the default).
global js: bool = false

export func use_js_journey(on: bool) {
  js = on
}

// The Journey, level by level.
export func journey() -> []Spec => if js { specs_js } else { specs_port }
`;
fs.writeFileSync(path.join(__dirname, '../journey.ents'), out);
console.log('wrote journey.ents: specs_js from', rel(jsFile) + ', specs_port from', rel(portFile));
