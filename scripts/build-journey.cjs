// Rebuild the sorted metadata index after changing the v2 generator. No maps or
// solutions are checked in: runtime generation still constructs every board.
const fs = require('node:fs'), path = require('node:path');
const G = require('../game-engine'), D = require('../difficulty'), L = require('../levels');
const levels = [];
for (let i = 0; i < 120; i++) {
  const rng = L.mulberry32(L.hashString('journey/2/size/' + i));
  const spec = { grid: i < 5 ? 'square' : i < 10 ? 'hex' : i % 2 ? 'hex' : 'square',
    difficulty: i < 10 ? 1 : 26 + 74 * (i - 10) / 109,
    size: i < 10 ? 4 + Math.floor(rng() * 5) : 4 + Math.floor(rng() * 57),
    mirrors: i >= 30 && i % 10 >= 4, springs: i >= 60 && [2, 7].includes(i % 10),
    seed: L.hashString('journey/2/map/' + i).toString(36).toUpperCase() };
  const b = D.generate(spec, G); levels.push({ ...spec, par: b.par });
  process.stderr.write(`${i + 1}: ${b.grid} ${b.ropes.length} ropes / ${b.par} taps\n`);
}
levels.sort((a, b) => a.par * b.size - b.par * a.size || a.size - b.size || a.grid.localeCompare(b.grid) * -1 || a.seed.localeCompare(b.seed));
const output = '// Generated by scripts/build-journey.cjs. Metadata only; maps are built from seeds.\n' +
  '(function(root){const levels=' + JSON.stringify(levels, null, 2) + ';if(typeof module!=="undefined"&&module.exports)module.exports=levels;else root.MFJourney=levels;})(globalThis);\n';
fs.writeFileSync(path.join(__dirname, '../journey.js'), output);
