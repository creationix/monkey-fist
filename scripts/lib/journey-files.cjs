// The Journey builder's two outputs. The game loads only grid-journey.js: each
// level's specification and map seed, which is all generation reads. Everything
// the builder measured goes to a JSON file beside the builder, for tests and docs.
'use strict';
const path = require('node:path');
// The fields grid-generator.js reads from a level specification.
const RUNTIME_FIELDS = ['grid', 'W', 'H', 'difficulty', 'mirrors', 'springs', 'seed', 'minMirrors', 'minSprings', 'requireSlide'];
const runtimeOf = level => Object.fromEntries(RUNTIME_FIELDS.filter(k => level[k] !== undefined).map(k => [k, level[k]]));
const measurementsPath = out => path.resolve(out) === path.resolve(__dirname, '../../grid-journey.js')
  ? path.join(__dirname, '../grid-journey-measurements.json') : out.replace(/\.js$/, '') + '-measurements.json';
function runtimeSource(levels, seed) {
  return '// Generated by scripts/build-grid-journey.cjs from seed ' + seed + '. Specifications and map seeds only; the game builds\n' +
    '// each map from them. The builder\'s measurements are in scripts/grid-journey-measurements.json.\n' +
    '(function(root){const levels=[\n' + levels.map(level => JSON.stringify(runtimeOf(level))).join(',\n') +
    '\n];if(typeof module!=="undefined"&&module.exports)module.exports=levels;else root.MFGridJourney=levels;})(globalThis);\n';
}
module.exports = { RUNTIME_FIELDS, runtimeOf, runtimeSource, measurementsPath };
